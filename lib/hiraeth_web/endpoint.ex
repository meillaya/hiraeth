defmodule HiraethWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :hiraeth

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_hiraeth_key",
    signing_salt: "jSFG9qif",
    encryption_salt: "6c8725d9413d2d6927c5dec6c9f9a7bf",
    secure: Application.compile_env(:hiraeth, :session_cookie_secure, false),
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  # Cover paths are content-addressed by the SHA-256 of the source URL, so they
  # can be cached by the browser for a day. The proxy refill path sets the same
  # header. A takedown removes the local and R2 copies immediately; a browser
  # that already cached the image may keep it until the max-age expires.
  plug Plug.Static,
    at: "/",
    from: :hiraeth,
    gzip: not code_reloading?,
    only: HiraethWeb.static_paths(),
    raise_on_missing_only: code_reloading?,
    headers: {__MODULE__, :static_headers, []}

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :hiraeth
  end

  # RequestLogger is a dev/test debugging aid; it is gated out of prod
  # (config/prod.exs sets :disable_request_logger to true).
  unless Application.compile_env(:hiraeth, :disable_request_logger, false) do
    plug Phoenix.LiveDashboard.RequestLogger,
      param_key: "request_logger",
      cookie_key: "request_logger"
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Every route is a GET or a LiveView socket, so no request body is consumed.
  # Parsing urlencoded and JSON keeps LiveView params working; multipart is
  # dropped and the body cap is small to deny unauthenticated temp-file writes.
  plug Plug.Parsers,
    parsers: [:urlencoded, :json],
    pass: ["*/*"],
    length: 100_000,
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug HiraethWeb.Router

  @doc false
  def static_headers(conn) do
    if String.starts_with?(conn.request_path, "/covers/cache/") do
      [
        {"cache-control", cover_cache_control(conn.request_path)},
        {"x-content-type-options", "nosniff"}
      ]
    else
      []
    end
  end

  # Responsive variants carry a content hash in their filename, so a cached
  # copy can never go stale. Originals and thumbnails keep the day-long cache.
  defp cover_cache_control(path) do
    if Hiraeth.Covers.responsive_variant_path?(path) do
      "public, max-age=31536000, immutable"
    else
      "public, max-age=86400"
    end
  end
end
